// GetAll returns every user.
//
// ORDER BY is not decoration — without it Postgres may return rows in any
// order, and that order can change between identical calls. Add LIMIT/OFFSET
// (see the notes at the bottom) before this table gets big.
func (h *UserHandler) GetAll(w http.ResponseWriter, r *http.Request) {
	const query = `SELECT ` + userCols + ` FROM users ORDER BY id`

	rows, err := h.DB.Query(r.Context(), query)
	if err != nil {
		slog.Error("users: select all", "error", err)
		http.Error(w, "Database error", http.StatusInternalServerError)
		return
	}

	users, err := collectUsers(rows, 0)
	if err != nil {
		slog.Error("users: select all", "error", err)
		http.Error(w, "Database error", http.StatusInternalServerError)
		return
	}

	// An empty result must encode as [] and not null, which is why collectUsers
	// returns a made slice rather than a nil one.
	writeJSON(w, http.StatusOK, users)
}

// GetOne returns a single user by path id.
//
//	GET /users/{id}
func (h *UserHandler) GetOne(w http.ResponseWriter, r *http.Request) {
	id, err := strconv.Atoi(r.PathValue("id")) // Go 1.22+ path patterns
	if err != nil {
		http.Error(w, "Invalid user ID", http.StatusBadRequest)
		return
	}

	const query = `SELECT ` + userCols + ` FROM users WHERE id = $1`

	var u User
	if err := scanUser(h.DB.QueryRow(r.Context(), query, id), &u); err != nil {
		// QueryRow folds "no rows" into a Scan error, so this is where a 404
		// gets told apart from a real failure.
		if errors.Is(err, pgx.ErrNoRows) {
			http.Error(w, "User not found", http.StatusNotFound)
			return
		}
		slog.Error("users: select one", "error", err, "id", id)
		http.Error(w, "Database error", http.StatusInternalServerError)
		return
	}

	writeJSON(w, http.StatusOK, u)
}

