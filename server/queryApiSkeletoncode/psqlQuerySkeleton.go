// Package queryapiskeletonc
// ode is a copy-paste reference for the Postgres
// queries and pgxpool calls this project keeps reaching for. Nothing here is
// wired into the running API — it lives outside the go_be_skeleton module and
// is never built by it.
//
// Every handler below assumes this table:
//
//	CREATE TABLE users (
//	    id        SERIAL PRIMARY KEY,
//	    email     TEXT NOT NULL UNIQUE,   -- the upserts conflict on this
//	    name      TEXT NOT NULL,
//	    age       INT  NOT NULL,
//	    weight    DOUBLE PRECISION NOT NULL,
//	    gender    TEXT NOT NULL,
//	    height_cm DOUBLE PRECISION NOT NULL
//	);
//
// Which pgxpool call to reach for:
//
//	Exec      → writes you only need a row count from (UPDATE, DELETE)
//	QueryRow  → exactly one row back; pgx.ErrNoRows when there is none
//	Query     → zero-to-many rows back, including writes with RETURNING
//
// A single SQL statement is atomic on its own — Postgres wraps it in an
// implicit transaction — so none of these need db.Begin. Reach for an explicit
// transaction only once a handler issues two statements that must both land.
package queryapiskeletoncode

import (
	"encoding/json"
	"errors"
	"log/slog"
	"net/http"
	"strconv"

	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgconn"
	"github.com/jackc/pgx/v5/pgxpool"
)

type User struct {
	ID       int     `json:"id"`
	Email    string  `json:"email"`
	Name     string  `json:"name"`
	Age      int     `json:"age"`
	Weight   float64 `json:"weight"`
	Gender   string  `json:"gender"`
	HeightCm float64 `json:"height_cm"`
}

type UserHandler struct {
	DB *pgxpool.Pool
}

// userCols is the column order every query and scan in this file agrees on.
// Scans are positional, so a SELECT list and its Scan must not drift apart.
const userCols = `id, email, name, age, weight, gender, height_cm`

// scanUser reads one row in userCols order. pgx.Rows satisfies pgx.Row, so this
// works both for a QueryRow result and for a row inside a Query loop.
func scanUser(row pgx.Row, u *User) error {
	return row.Scan(&u.ID, &u.Email, &u.Name, &u.Age, &u.Weight, &u.Gender, &u.HeightCm)
}

// writeJSON sets the header, then the status, then the body — in that order.
// Header().Set after WriteHeader is silently ignored, and the first Write
// implies WriteHeader(200), so an early Encode locks in the wrong status.
func writeJSON(w http.ResponseWriter, status int, v any) {
	w.Header().Set("Content-Type", "application/json")
	w.WriteHeader(status)
	if v != nil {
		_ = json.NewEncoder(w).Encode(v)
	}
}

// isUniqueViolation reports whether err is Postgres 23505 — a UNIQUE constraint
// rejection. Worth special-casing: it is the caller's fault (409), not a 500.
func isUniqueViolation(err error) bool {
	var pgErr *pgconn.PgError
	return errors.As(err, &pgErr) && pgErr.Code == "23505"
}

// columns lifts one field out of every user, so the bulk statements below can
// pass one array per column instead of building $1..$60 by hand.
func columns(users []User) (emails, names, genders []string, ages []int64, weights, heights []float64) {
	emails = make([]string, len(users))
	names = make([]string, len(users))
	genders = make([]string, len(users))
	ages = make([]int64, len(users))
	weights = make([]float64, len(users))
	heights = make([]float64, len(users))
	for i, u := range users {
		emails[i] = u.Email
		names[i] = u.Name
		genders[i] = u.Gender
		ages[i] = int64(u.Age)
		weights[i] = u.Weight
		heights[i] = u.HeightCm
	}
	return
}

// collectUsers drains rows into a slice.
//
// The rows.Err() check is the important part: pgx reports most server-side
// failures from Next/Err rather than from Query, so a constraint violation on a
// RETURNING write is silently swallowed without it.
func collectUsers(rows pgx.Rows, capHint int) ([]User, error) {
	defer rows.Close()

	out := make([]User, 0, capHint)
	for rows.Next() {
		var u User
		if err := scanUser(rows, &u); err != nil {
			return nil, err
		}
		out = append(out, u)
	}
	return out, rows.Err()
}

