// EditOne replaces every field of one user.
//
// RETURNING plus pgx.ErrNoRows distinguishes "no such id" from success in a
// single round trip. The Exec alternative is fine too — it just reports the
// same thing through a row count instead:
//
//	tag, err := h.DB.Exec(ctx, query, ...)
//	if tag.RowsAffected() == 0 { /* 404 */ }
//
//	PUT /users/{id}
func (h *UserHandler) EditOne(w http.ResponseWriter, r *http.Request) {
	id, err := strconv.Atoi(r.PathValue("id"))
	if err != nil {
		http.Error(w, "Invalid user ID", http.StatusBadRequest)
		return
	}

	var u User
	if err := json.NewDecoder(r.Body).Decode(&u); err != nil {
		http.Error(w, "Invalid request body", http.StatusBadRequest)
		return
	}

	const query = `
		UPDATE users
		SET email     = $1,
		    name      = $2,
		    age       = $3,
		    weight    = $4,
		    gender    = $5,
		    height_cm = $6
		WHERE id = $7
		RETURNING ` + userCols

	row := h.DB.QueryRow(r.Context(), query, u.Email, u.Name, u.Age, u.Weight, u.Gender, u.HeightCm, id)
	if err := scanUser(row, &u); err != nil {
		if errors.Is(err, pgx.ErrNoRows) {
			http.Error(w, "User not found", http.StatusNotFound)
			return
		}
		if isUniqueViolation(err) {
			http.Error(w, "A user with that email already exists", http.StatusConflict)
			return
		}
		slog.Error("users: update one", "error", err, "id", id)
		http.Error(w, "Failed to update user", http.StatusInternalServerError)
		return
	}

	writeJSON(w, http.StatusOK, u)
}

// EditMany updates a list of users, each with its own values, in ONE statement.
//
// The trick is UPDATE ... FROM unnest(...) AS v(...): unnest builds a virtual
// table of new values and the WHERE joins it to the real one on id. The naive
// alternative — a Go loop issuing one UPDATE per user — costs a round trip each
// and needs an explicit transaction to stay atomic.
//
// Ids not present in the table simply match nothing; compare len(stored) with
// len(users) to detect that.
//
//	PATCH /users/bulk
//	[{"id":1,"email":"a@b.c", ...}, {"id":2, ...}]
func (h *UserHandler) EditMany(w http.ResponseWriter, r *http.Request) {
	var users []User
	if err := json.NewDecoder(r.Body).Decode(&users); err != nil {
		http.Error(w, "Invalid request body — expected a JSON array", http.StatusBadRequest)
		return
	}
	if len(users) == 0 {
		writeJSON(w, http.StatusOK, []User{})
		return
	}

	const query = `
		UPDATE users AS u
		SET email     = v.email,
		    name      = v.name,
		    age       = v.age,
		    weight    = v.weight,
		    gender    = v.gender,
		    height_cm = v.height_cm
		FROM unnest(
			$1::bigint[],
			$2::text[],
			$3::text[],
			$4::bigint[],
			$5::double precision[],
			$6::text[],
			$7::double precision[]
		) AS v(id, email, name, age, weight, gender, height_cm)
		WHERE u.id = v.id
		RETURNING u.id, u.email, u.name, u.age, u.weight, u.gender, u.height_cm`

	ids := make([]int64, len(users))
	for i, u := range users {
		ids[i] = int64(u.ID)
	}
	emails, names, genders, ages, weights, heights := columns(users)

	rows, err := h.DB.Query(r.Context(), query, ids, emails, names, ages, weights, genders, heights)
	if err != nil {
		slog.Error("users: update many", "error", err)
		http.Error(w, "Failed to update users", http.StatusInternalServerError)
		return
	}

	stored, err := collectUsers(rows, len(users))
	if err != nil {
		slog.Error("users: update many", "error", err)
		http.Error(w, "Failed to update users", http.StatusInternalServerError)
		return
	}

	writeJSON(w, http.StatusOK, stored)
}

