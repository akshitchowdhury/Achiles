// AddOne inserts a single user and returns the stored row.
//
// RETURNING is what makes this a QueryRow rather than an Exec — the id is
// generated by the SERIAL default, so it only exists after the insert runs.
//
//	POST /users
//	{"email":"a@b.c","name":"Ada","age":30,"weight":62.5,"gender":"Female","height_cm":170}
func (h *UserHandler) AddOne(w http.ResponseWriter, r *http.Request) {
	var u User
	if err := json.NewDecoder(r.Body).Decode(&u); err != nil {
		http.Error(w, "Invalid request body", http.StatusBadRequest)
		return
	}

	const query = `
		INSERT INTO users (email, name, age, weight, gender, height_cm)
		VALUES ($1, $2, $3, $4, $5, $6)
		RETURNING ` + userCols

	row := h.DB.QueryRow(r.Context(), query, u.Email, u.Name, u.Age, u.Weight, u.Gender, u.HeightCm)
	if err := scanUser(row, &u); err != nil {
		if isUniqueViolation(err) {
			http.Error(w, "A user with that email already exists", http.StatusConflict)
			return
		}
		slog.Error("users: insert", "error", err)
		http.Error(w, "Failed to insert user", http.StatusInternalServerError)
		return
	}

	writeJSON(w, http.StatusCreated, u)
}

// AddAll inserts a whole JSON array of users in ONE statement.
//
// unnest turns the six array parameters into rows, which keeps the batch size a
// runtime detail instead of something baked into the SQL. Because it is a
// single statement it is all-or-nothing: one bad row rolls back the rest, with
// no transaction needed.
//
// The ::casts are explicit because the parameters arrive as bigint[] and
// double precision[]; Postgres assignment-casts them into the int and
// double precision columns.
//
//	POST /users/bulk
//	[{"email":"a@b.c", ...}, {"email":"d@e.f", ...}]
func (h *UserHandler) AddAll(w http.ResponseWriter, r *http.Request) {
	var users []User
	if err := json.NewDecoder(r.Body).Decode(&users); err != nil {
		http.Error(w, "Invalid request body — expected a JSON array", http.StatusBadRequest)
		return
	}
	if len(users) == 0 {
		writeJSON(w, http.StatusOK, []User{})
		return
	}

	const query = `
		INSERT INTO users (email, name, age, weight, gender, height_cm)
		SELECT * FROM unnest(
			$1::text[],
			$2::text[],
			$3::bigint[],
			$4::double precision[],
			$5::text[],
			$6::double precision[]
		)
		RETURNING ` + userCols

	emails, names, genders, ages, weights, heights := columns(users)

	rows, err := h.DB.Query(r.Context(), query, emails, names, ages, weights, genders, heights)
	if err != nil {
		slog.Error("users: bulk insert", "error", err)
		http.Error(w, "Failed to insert users", http.StatusInternalServerError)
		return
	}

	stored, err := collectUsers(rows, len(users))
	if err != nil {
		if isUniqueViolation(err) {
			http.Error(w, "One of those emails already exists", http.StatusConflict)
			return
		}
		slog.Error("users: bulk insert", "error", err)
		http.Error(w, "Failed to insert users", http.StatusInternalServerError)
		return
	}

	writeJSON(w, http.StatusCreated, stored)
}

