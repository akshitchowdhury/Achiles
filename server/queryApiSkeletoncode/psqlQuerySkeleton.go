// DeleteOne removes one user by id.
//
// Nothing comes back, so this is an Exec: the row count is the only signal, and
// zero means the id never existed.
//
//	DELETE /users/{id}
func (h *UserHandler) DeleteOne(w http.ResponseWriter, r *http.Request) {
	id, err := strconv.Atoi(r.PathValue("id"))
	if err != nil {
		http.Error(w, "Invalid user ID", http.StatusBadRequest)
		return
	}

	const query = `DELETE FROM users WHERE id = $1`

	tag, err := h.DB.Exec(r.Context(), query, id)
	if err != nil {
		slog.Error("users: delete one", "error", err, "id", id)
		http.Error(w, "Failed to delete user", http.StatusInternalServerError)
		return
	}
	if tag.RowsAffected() == 0 {
		http.Error(w, "User not found", http.StatusNotFound)
		return
	}

	// 204 says "done, nothing to send" — do not also write a body.
	w.WriteHeader(http.StatusNoContent)
}

// DeleteAll empties the table.
//
// Destructive and trivially reachable, so it demands a deliberate ?confirm=true
// rather than firing on a stray request. Ship it behind auth or not at all.
//
// DELETE is the right verb here: it fires triggers, respects foreign keys row
// by row, and can be rolled back cheaply. TRUNCATE users RESTART IDENTITY is
// far faster on a large table but takes an ACCESS EXCLUSIVE lock and fails
// outright if another table references this one.
//
//	DELETE /users?confirm=true
func (h *UserHandler) DeleteAll(w http.ResponseWriter, r *http.Request) {
	if r.URL.Query().Get("confirm") != "true" {
		http.Error(w, "Refusing to delete every user without ?confirm=true", http.StatusBadRequest)
		return
	}

	const query = `DELETE FROM users`

	tag, err := h.DB.Exec(r.Context(), query)
	if err != nil {
		slog.Error("users: delete all", "error", err)
		http.Error(w, "Failed to delete users", http.StatusInternalServerError)
		return
	}

	writeJSON(w, http.StatusOK, map[string]int64{"deleted": tag.RowsAffected()})
}

// ---------------------------------------------------------------------------
// Variants worth remembering
// ---------------------------------------------------------------------------
//
// Pagination — always paired with a stable ORDER BY:
//
//	SELECT id, email, name FROM users ORDER BY id LIMIT $1 OFFSET $2
//
// Same new value across many rows — much simpler than unnest when only the ids
// vary. = ANY($1::bigint[]) takes one array parameter instead of $1..$n:
//
//	UPDATE users SET gender = $1 WHERE id = ANY($2::bigint[])
//	DELETE FROM users WHERE id = ANY($1::bigint[])
//
// Count and existence — QueryRow always returns exactly one row here, so
// pgx.ErrNoRows is impossible and EXISTS beats COUNT(*) > 0 because it stops at
// the first match:
//
//	var n int
//	h.DB.QueryRow(ctx, `SELECT count(*) FROM users`).Scan(&n)
//
//	var exists bool
//	h.DB.QueryRow(ctx, `SELECT EXISTS(SELECT 1 FROM users WHERE email = $1)`, email).Scan(&exists)
//
// Join across tables — prefix every column, and scan in exactly SELECT order:
//
//	SELECT u.id, u.name, s.bmi_value, s.bmr_value, s.verdict
//	FROM users u
//	JOIN user_specs s ON u.id = s.user_id
//	WHERE u.id = $1
//
// A LEFT JOIN puts NULLs in the right-hand columns when there is no match, so
// scan those into *float64 / sql.NullFloat64 rather than float64.
//
// Explicit transaction — for two or more statements that must land together,
// e.g. insert a user then their specs row using the returned id. Rollback after
// a successful Commit is a no-op, so deferring it unconditionally is the
// idiom:
//
//	tx, err := h.DB.Begin(ctx)
//	if err != nil { return err }
//	defer tx.Rollback(ctx)
//
//	var id int
//	if err := tx.QueryRow(ctx, insertUser, ...).Scan(&id); err != nil { return err }
//	if _, err := tx.Exec(ctx, insertSpecs, id, ...); err != nil { return err }
//
//	return tx.Commit(ctx)
//
// CopyFrom — the fastest bulk load by a wide margin, but it is a raw stream:
// no ON CONFLICT, no RETURNING. Good for seeding an empty table, useless for
// upserts:
//
//	_, err := h.DB.CopyFrom(ctx,
//	    pgx.Identifier{"users"},
//	    []string{"email", "name", "age", "weight", "gender", "height_cm"},
//	    pgx.CopyFromSlice(len(users), func(i int) ([]any, error) {
//	        u := users[i]
//	        return []any{u.Email, u.Name, u.Age, u.Weight, u.Gender, u.HeightCm}, nil
//	    }),
//	)
//
// pgx.Batch — many *different* statements in one round trip. Queue them inside
// a transaction if they must all land; a batch is not atomic by itself:
//
//	batch := &pgx.Batch{}
//	for _, u := range users {
//	    batch.Queue(`INSERT INTO users (...) VALUES ($1, ...)`, u.Email /* ... */)
//	}
//	results := h.DB.SendBatch(ctx, batch)
//	defer results.Close()
//
// pgx.CollectRows — replaces the manual scan loop. RowToStructByName matches on
// `db:"..."` struct tags (falling back to lowercased field names), so User would
// need db tags before this works:
//
//	rows, err := h.DB.Query(ctx, query)
//	if err != nil { return nil, err }
//	users, err := pgx.CollectRows(rows, pgx.RowToStructByName[User])
//
// Partial update — the SETs above overwrite every column, so a PATCH that omits
// a field would zero it. Either decode into a struct of pointers and build the
// SET list from the non-nil ones, or lean on COALESCE to keep the current value
// when a parameter arrives NULL:
//
//	UPDATE users SET name = COALESCE($1, name), age = COALESCE($2, age) WHERE id = $3
