// UpsertOne inserts a user, or updates the existing row with that email.
//
// ON CONFLICT needs a real UNIQUE constraint on the named column or Postgres
// errors out. EXCLUDED is the row that was proposed for insertion; note that id
// and email are deliberately not overwritten from it.
func (h *UserHandler) UpsertOne(w http.ResponseWriter, r *http.Request) {
	var u User
	if err := json.NewDecoder(r.Body).Decode(&u); err != nil {
		http.Error(w, "Invalid request body", http.StatusBadRequest)
		return
	}

	const query = `
		INSERT INTO users (email, name, age, weight, gender, height_cm)
		VALUES ($1, $2, $3, $4, $5, $6)
		ON CONFLICT (email) DO UPDATE
		SET name      = EXCLUDED.name,
		    age       = EXCLUDED.age,
		    weight    = EXCLUDED.weight,
		    gender    = EXCLUDED.gender,
		    height_cm = EXCLUDED.height_cm
		RETURNING ` + userCols

	row := h.DB.QueryRow(r.Context(), query, u.Email, u.Name, u.Age, u.Weight, u.Gender, u.HeightCm)
	if err := scanUser(row, &u); err != nil {
		slog.Error("users: upsert", "error", err)
		http.Error(w, "Failed to save user", http.StatusInternalServerError)
		return
	}

	writeJSON(w, http.StatusOK, u)
}

// UpsertAll is the bulk form: seed-or-refresh a whole list in one statement.
// This is the shape to reach for when populating reference data on boot.
//
// One sharp edge: if the same email appears twice in the batch, Postgres fails
// with "ON CONFLICT DO UPDATE command cannot affect row a second time". Dedupe
// in Go first, or wrap the source in SELECT DISTINCT ON (email).
func (h *UserHandler) UpsertAll(w http.ResponseWriter, r *http.Request) {
	var users []User
	if err := json.NewDecoder(r.Body).Decode(&users); err != nil {
		http.Error(w, "Invalid request body — expected a JSON array", http.StatusBadRequest)
		return
	}
	if len(users) == 0 {
		writeJSON(w, http.StatusOK, []User{})
		return
	}

	const query = `
		INSERT INTO users (email, name, age, weight, gender, height_cm)
		SELECT * FROM unnest(
			$1::text[],
			$2::text[],
			$3::bigint[],
			$4::double precision[],
			$5::text[],
			$6::double precision[]
		)
		ON CONFLICT (email) DO UPDATE
		SET name      = EXCLUDED.name,
		    age       = EXCLUDED.age,
		    weight    = EXCLUDED.weight,
		    gender    = EXCLUDED.gender,
		    height_cm = EXCLUDED.height_cm
		RETURNING ` + userCols

	emails, names, genders, ages, weights, heights := columns(users)

	rows, err := h.DB.Query(r.Context(), query, emails, names, ages, weights, genders, heights)
	if err != nil {
		slog.Error("users: bulk upsert", "error", err)
		http.Error(w, "Failed to save users", http.StatusInternalServerError)
		return
	}

	stored, err := collectUsers(rows, len(users))
	if err != nil {
		slog.Error("users: bulk upsert", "error", err)
		http.Error(w, "Failed to save users", http.StatusInternalServerError)
		return
	}

	writeJSON(w, http.StatusOK, stored)
}

